-- Compact six-table target. Does not migrate data or switch the live API.
-- If an older smarttour_demo design exists, stop rather than silently keep it.
BEGIN;
CREATE SCHEMA IF NOT EXISTS smarttour_demo;
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
             WHERE table_schema='smarttour_demo' AND table_name='places'
               AND column_name='category') THEN
    RAISE EXCEPTION 'Older smarttour_demo design exists. Back up and migrate it before applying this file.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS smarttour_demo.users (
  id text PRIMARY KEY,
  username text NOT NULL UNIQUE,
  display_name text NOT NULL,
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'user',
  enabled boolean NOT NULL DEFAULT true,
  settings jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(settings)='object')
);

CREATE TABLE IF NOT EXISTS smarttour_demo.places (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text REFERENCES smarttour_demo.users(id) ON DELETE SET NULL,
  name text NOT NULL,
  address text,
  latitude double precision CHECK(latitude BETWEEN -90 AND 90),
  longitude double precision CHECK(longitude BETWEEN -180 AND 180),
  introduction text NOT NULL,
  settings jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(settings)='object'),
  CHECK((latitude IS NULL) = (longitude IS NULL))
);

CREATE TABLE IF NOT EXISTS smarttour_demo.place_images (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  place_id bigint NOT NULL REFERENCES smarttour_demo.places(id) ON DELETE CASCADE,
  url text NOT NULL,
  caption text NOT NULL DEFAULT '',
  ordinal integer NOT NULL CHECK(ordinal >= 0),
  is_cover boolean NOT NULL DEFAULT false,
  metadata jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(metadata)='object'),
  UNIQUE(place_id, ordinal)
);
CREATE UNIQUE INDEX IF NOT EXISTS one_cover_per_place
  ON smarttour_demo.place_images(place_id) WHERE is_cover;

-- Vietnamese source uses language_code='vi'; translated rows use other codes.
-- Audio bytes remain in file/object storage.
CREATE TABLE IF NOT EXISTS smarttour_demo.place_narrations (
  id text PRIMARY KEY,
  place_id bigint NOT NULL REFERENCES smarttour_demo.places(id) ON DELETE CASCADE,
  language_code text NOT NULL CHECK(language_code IN ('vi','en','zh','ja','ko','fr')),
  narration_text text NOT NULL,
  audio_path text,
  status text NOT NULL CHECK(status IN ('draft','approved','archived')),
  version text NOT NULL,
  metadata jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(metadata)='object'),
  UNIQUE(place_id, language_code, version)
);
CREATE UNIQUE INDEX IF NOT EXISTS one_approved_narration_per_language
  ON smarttour_demo.place_narrations(place_id, language_code) WHERE status='approved';

-- One row per tab; count DISTINCT device_id for active browsers.
CREATE TABLE IF NOT EXISTS smarttour_demo.visitor_sessions (
  id text PRIMARY KEY,
  device_id text NOT NULL,
  device_info jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(device_info)='object'),
  started_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  ended_at timestamptz
);
CREATE INDEX IF NOT EXISTS active_sessions
  ON smarttour_demo.visitor_sessions(last_seen_at, device_id) WHERE ended_at IS NULL;

CREATE TABLE IF NOT EXISTS smarttour_demo.activity_logs (
  id text PRIMARY KEY,
  kind text NOT NULL CHECK(kind IN ('view','play','admin')),
  user_id text REFERENCES smarttour_demo.users(id) ON DELETE SET NULL,
  device_id text,
  place_id bigint REFERENCES smarttour_demo.places(id) ON DELETE SET NULL,
  consent boolean NOT NULL DEFAULT false,
  details jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(details)='object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK(kind='admin' OR (consent AND device_id IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS activity_time ON smarttour_demo.activity_logs(created_at DESC);

-- Backend access only. No browser Data API grants.
ALTER TABLE smarttour_demo.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE smarttour_demo.places ENABLE ROW LEVEL SECURITY;
ALTER TABLE smarttour_demo.place_images ENABLE ROW LEVEL SECURITY;
ALTER TABLE smarttour_demo.place_narrations ENABLE ROW LEVEL SECURITY;
ALTER TABLE smarttour_demo.visitor_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE smarttour_demo.activity_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON SCHEMA smarttour_demo FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA smarttour_demo FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA smarttour_demo FROM PUBLIC;
COMMIT;
