-- PostgreSQL/Supabase relational target schema. Backend adapter and data import
-- are a separate migration step; running this does not switch the live API.
BEGIN;
CREATE SCHEMA IF NOT EXISTS smarttour;

CREATE TABLE IF NOT EXISTS smarttour.schema_migrations (
  version text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS smarttour.app_roles (
  name text PRIMARY KEY, built_in boolean NOT NULL DEFAULT false
);
CREATE TABLE IF NOT EXISTS smarttour.permissions (code text PRIMARY KEY);
CREATE TABLE IF NOT EXISTS smarttour.role_permissions (
  role_name text REFERENCES smarttour.app_roles(name) ON DELETE CASCADE,
  permission_code text REFERENCES smarttour.permissions(code) ON DELETE CASCADE,
  PRIMARY KEY(role_name, permission_code)
);
-- Keep existing application authentication. These are not Supabase Auth users.
CREATE TABLE IF NOT EXISTS smarttour.app_users (
  id text PRIMARY KEY, username text NOT NULL UNIQUE, display_name text NOT NULL,
  password_hash text NOT NULL, role_name text NOT NULL REFERENCES smarttour.app_roles(name),
  verified boolean NOT NULL DEFAULT false, enabled boolean NOT NULL DEFAULT true,
  must_change_password boolean NOT NULL DEFAULT false, security_stamp text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS smarttour.places (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL, category text NOT NULL, description_vi text NOT NULL,
  region text NOT NULL DEFAULT 'district1', owner_id text REFERENCES smarttour.app_users(id) ON DELETE SET NULL,
  address text, latitude double precision CHECK(latitude BETWEEN -90 AND 90),
  longitude double precision CHECK(longitude BETWEEN -180 AND 180),
  location_verified boolean NOT NULL DEFAULT false, is_demo boolean NOT NULL DEFAULT true,
  is_active boolean NOT NULL DEFAULT false, source_url text, address_source_url text, location_source_url text,
  trigger_radius integer NOT NULL DEFAULT 30 CHECK(trigger_radius > 0), audio_priority integer NOT NULL DEFAULT 0,
  audio_status text NOT NULL DEFAULT 'missing', activation_requested boolean NOT NULL DEFAULT false,
  ready_english_hash text, updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK(NOT location_verified OR (latitude IS NOT NULL AND longitude IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS smarttour.place_photos (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  place_id bigint NOT NULL REFERENCES smarttour.places(id) ON DELETE CASCADE,
  ordinal integer NOT NULL CHECK(ordinal >= 0), url text NOT NULL, caption text NOT NULL DEFAULT '',
  credit text NOT NULL DEFAULT '', source_url text, focus_y integer NOT NULL DEFAULT 50 CHECK(focus_y BETWEEN 0 AND 100),
  is_cover boolean NOT NULL DEFAULT false, UNIQUE(place_id, ordinal)
);
CREATE UNIQUE INDEX IF NOT EXISTS one_cover_per_place ON smarttour.place_photos(place_id) WHERE is_cover;
CREATE TABLE IF NOT EXISTS smarttour.narration_sources (
  source_hash text PRIMARY KEY, text_vi text NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS smarttour.place_narration_sources (
  place_id bigint PRIMARY KEY REFERENCES smarttour.places(id) ON DELETE CASCADE,
  source_hash text NOT NULL REFERENCES smarttour.narration_sources(source_hash)
);
CREATE TABLE IF NOT EXISTS smarttour.translation_drafts (
  id text PRIMARY KEY, place_id bigint NOT NULL REFERENCES smarttour.places(id) ON DELETE CASCADE,
  source_hash text NOT NULL REFERENCES smarttour.narration_sources(source_hash),
  language_code text NOT NULL CHECK(language_code IN ('vi','en','zh','ja','ko','fr')),
  translated_text text NOT NULL, status text NOT NULL, provider text,
  created_by text REFERENCES smarttour.app_users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(), review_note text NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS smarttour.approved_translations (
  source_hash text REFERENCES smarttour.narration_sources(source_hash),
  language_code text CHECK(language_code IN ('vi','en','zh','ja','ko','fr')),
  translated_text text NOT NULL, revision text NOT NULL,
  reviewer_id text REFERENCES smarttour.app_users(id) ON DELETE SET NULL,
  approved_at timestamptz NOT NULL, PRIMARY KEY(source_hash, language_code)
);
CREATE TABLE IF NOT EXISTS smarttour.audio_assets (
  content_key text PRIMARY KEY, source_hash text NOT NULL REFERENCES smarttour.narration_sources(source_hash),
  language_code text NOT NULL CHECK(language_code IN ('vi','en','zh','ja','ko','fr')),
  revision text, voice text NOT NULL, provider text NOT NULL, storage_path text NOT NULL,
  sha256 text NOT NULL, bytes bigint NOT NULL CHECK(bytes > 0), created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS smarttour.menu_items (
  id text PRIMARY KEY, place_id bigint NOT NULL REFERENCES smarttour.places(id) ON DELETE CASCADE,
  name text NOT NULL, description text NOT NULL DEFAULT '', price numeric(14,2) CHECK(price >= 0)
);
CREATE TABLE IF NOT EXISTS smarttour.moderation_requests (
  id text PRIMARY KEY, kind text NOT NULL, user_id text NOT NULL REFERENCES smarttour.app_users(id),
  place_id bigint REFERENCES smarttour.places(id) ON DELETE SET NULL,
  status text NOT NULL CHECK(status IN ('pending','approved','rejected')),
  proposed_place jsonb, applicant_note text NOT NULL DEFAULT '', admin_note text NOT NULL DEFAULT '',
  expected_place_version timestamptz, created_at timestamptz, reviewed_at timestamptz
);
CREATE TABLE IF NOT EXISTS smarttour.notifications (
  id text PRIMARY KEY, user_id text NOT NULL REFERENCES smarttour.app_users(id) ON DELETE CASCADE,
  review_id text REFERENCES smarttour.moderation_requests(id) ON DELETE SET NULL,
  place_id bigint REFERENCES smarttour.places(id) ON DELETE SET NULL,
  message text NOT NULL, is_read boolean NOT NULL DEFAULT false, created_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS smarttour.refresh_sessions (
  token_hash text PRIMARY KEY, user_id text NOT NULL REFERENCES smarttour.app_users(id) ON DELETE CASCADE,
  security_stamp text NOT NULL, expires_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS smarttour.audit_entries (
  id text PRIMARY KEY, actor_id text NOT NULL, action text NOT NULL, resource text NOT NULL, created_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS smarttour.anonymous_visitors (
  id uuid PRIMARY KEY, browser text NOT NULL DEFAULT 'Other', operating_system text NOT NULL DEFAULT 'Other',
  device_type text NOT NULL DEFAULT 'Unknown', first_seen_at timestamptz NOT NULL DEFAULT now(), last_seen_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS smarttour.visitor_sessions (
  id uuid PRIMARY KEY, visitor_id uuid NOT NULL REFERENCES smarttour.anonymous_visitors(id) ON DELETE CASCADE,
  started_at timestamptz NOT NULL DEFAULT now(), last_activity_at timestamptz NOT NULL DEFAULT now(), ended_at timestamptz
);
CREATE INDEX IF NOT EXISTS active_visitor_sessions ON smarttour.visitor_sessions(last_activity_at) WHERE ended_at IS NULL;
CREATE TABLE IF NOT EXISTS smarttour.analytics_events (
  id uuid PRIMARY KEY, visitor_id uuid NOT NULL REFERENCES smarttour.anonymous_visitors(id) ON DELETE CASCADE,
  place_id bigint REFERENCES smarttour.places(id) ON DELETE SET NULL,
  kind text NOT NULL CHECK(kind IN ('view','play','heartbeat')),
  language_code text NOT NULL CHECK(language_code IN ('vi','en','zh','ja','ko','fr')),
  consent boolean NOT NULL CHECK(consent), occurred_at timestamptz NOT NULL,
  processing_state text NOT NULL DEFAULT 'pending' CHECK(processing_state IN ('pending','processed'))
);
CREATE INDEX IF NOT EXISTS analytics_visitor_time ON smarttour.analytics_events(visitor_id, occurred_at DESC);
CREATE TABLE IF NOT EXISTS smarttour.audio_tasks (
  id text PRIMARY KEY, place_id bigint NOT NULL REFERENCES smarttour.places(id) ON DELETE CASCADE,
  languages text[] NOT NULL, status text NOT NULL, completed integer NOT NULL DEFAULT 0,
  error text, requested_by text NOT NULL, source_hash text REFERENCES smarttour.narration_sources(source_hash),
  created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, heartbeat_at timestamptz
);
CREATE TABLE IF NOT EXISTS smarttour.owner_identities (
  user_id text PRIMARY KEY REFERENCES smarttour.app_users(id) ON DELETE CASCADE,
  ciphertext text NOT NULL, expires_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS smarttour.runtime_locations (
  session_id uuid NOT NULL, hour timestamptz NOT NULL, latitude double precision NOT NULL,
  longitude double precision NOT NULL, accuracy double precision NOT NULL CHECK(accuracy >= 0),
  last_seen_at timestamptz NOT NULL, PRIMARY KEY(session_id, hour)
);
CREATE TABLE IF NOT EXISTS smarttour.revoked_visitors (
  visitor_id uuid NOT NULL, scope text NOT NULL CHECK(scope IN ('analytics','runtime')), expires_at timestamptz NOT NULL,
  PRIMARY KEY(visitor_id, scope)
);
CREATE TABLE IF NOT EXISTS smarttour.deleted_places (place_id bigint PRIMARY KEY, deleted_at timestamptz NOT NULL);
CREATE TABLE IF NOT EXISTS smarttour.ai_usage (quota_key text PRIMARY KEY, used integer NOT NULL CHECK(used >= 0));
CREATE TABLE IF NOT EXISTS smarttour.platform_metadata (
  id integer PRIMARY KEY CHECK(id=1), version bigint NOT NULL, sample_data_version integer NOT NULL,
  next_place_id bigint NOT NULL, updated_at timestamptz NOT NULL
);

-- App tables are accessed by the C# backend, not browser anon/authenticated keys.
DO $$ DECLARE item record; BEGIN
  FOR item IN SELECT tablename FROM pg_tables WHERE schemaname='smarttour' LOOP
    EXECUTE format('ALTER TABLE smarttour.%I ENABLE ROW LEVEL SECURITY', item.tablename);
  END LOOP;
END $$;
REVOKE ALL ON SCHEMA smarttour FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA smarttour FROM PUBLIC;
INSERT INTO smarttour.schema_migrations(version) VALUES ('001_relational_design') ON CONFLICT DO NOTHING;
COMMIT;
